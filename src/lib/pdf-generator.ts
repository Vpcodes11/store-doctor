import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { AuditAnalysisResult, FindingItem } from './analyzer';
import { AICopyAnalysis } from './ai-service';

export function generateAuditPdf(
  storeUrl: string,
  storeName: string,
  analysis: AuditAnalysisResult,
  aiCopy?: AICopyAnalysis
): Uint8Array {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // Helper for drawing header on secondary pages
  const drawPageHeader = (pageNumber: number) => {
    doc.setFillColor(15, 23, 42); // slate-900
    doc.rect(0, 0, pageWidth, 14, 'F');

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(16, 185, 129); // emerald-500
    doc.text('STOREDOCTOR™', 14, 9);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(148, 163, 184); // slate-400
    doc.text(`Conversion Audit: ${storeName}`, 48, 9);

    doc.setFontSize(8);
    doc.text(`Page ${pageNumber}`, pageWidth - 24, 9);
  };

  // Helper for drawing footer
  const drawPageFooter = () => {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      'Confidential CRO Audit Report • Generated by StoreDoctor AI Engine • storedoctor.io',
      14,
      pageHeight - 8
    );
  };

  // ==========================================
  // PAGE 1: COVER & EXECUTIVE SUMMARY
  // ==========================================
  // Dark header block
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageWidth, 45, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(255, 255, 255);
  doc.text('STOREDOCTOR™', 14, 22);

  doc.setFontSize(11);
  doc.setTextColor(16, 185, 129);
  doc.text('AI SHOPIFY CONVERSION AUDIT & ROADMAP', 14, 30);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225);
  doc.text(`Store URL: ${storeUrl}`, 14, 38);
  doc.text(`Date: ${new Date().toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' })}`, pageWidth - 45, 38);

  // Executive Score Card
  let yPos = 55;
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(14, yPos, pageWidth - 28, 38, 3, 3, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(14, yPos, pageWidth - 28, 38, 3, 3, 'S');

  // Overall Score Circle
  doc.setFillColor(15, 23, 42);
  doc.circle(36, yPos + 19, 14, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(16, 185, 129);
  doc.text(`${analysis.overallScore}`, 31, yPos + 22);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.text(`Store Health Grade: ${analysis.grade} (${analysis.overallScore}/100)`, 58, yPos + 14);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105);
  doc.text(
    `Estimated Monthly Revenue Leakage: ${analysis.revenueLeakageEstimate}`,
    58,
    yPos + 22
  );
  doc.text(
    `Prioritized Issues Identified: ${analysis.allFindings.length} conversion roadblocks`,
    58,
    yPos + 28
  );

  // Category Breakdown Table
  yPos = 100;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(15, 23, 42);
  doc.text('1. Category Health Breakdown', 14, yPos);

  const tableData = [
    ['Speed & Mobile Performance', `${analysis.categoryScores.speedMobile}/100`, analysis.categoryScores.speedMobile >= 70 ? 'Optimal' : 'Needs Optimization'],
    ['First Impression & Hero Clarity', `${analysis.categoryScores.firstImpression}/100`, analysis.categoryScores.firstImpression >= 70 ? 'Strong' : 'Action Required'],
    ['Trust, Reviews & Credibility', `${analysis.categoryScores.trustCredibility}/100`, analysis.categoryScores.trustCredibility >= 70 ? 'Solid' : 'High Friction'],
    ['Product Page Optimization', `${analysis.categoryScores.productPage}/100`, analysis.categoryScores.productPage >= 70 ? 'Good' : 'Conversion Leak'],
    ['Pricing, Offers & Thresholds', `${analysis.categoryScores.pricingOffers}/100`, analysis.categoryScores.pricingOffers >= 70 ? 'Competitive' : 'AOV Opportunity'],
    ['Checkout & Payment Friction', `${analysis.categoryScores.checkoutFriction}/100`, analysis.categoryScores.checkoutFriction >= 70 ? 'Low Friction' : 'Abandonment Signal'],
    ['Technical & On-Page SEO', `${analysis.categoryScores.seoBasics}/100`, analysis.categoryScores.seoBasics >= 70 ? 'Indexed' : 'Needs Cleanup'],
  ];

  autoTable(doc, {
    startY: yPos + 4,
    head: [['Evaluation Category', 'Score', 'Status']],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9,
    },
    styles: {
      fontSize: 9,
      cellPadding: 3,
    },
    columnStyles: {
      0: { cellWidth: 90 },
      1: { cellWidth: 35, fontStyle: 'bold' },
      2: { cellWidth: 55 },
    },
  });

  // Executive summary callout box at bottom of Page 1
  const finalY = (doc as any).lastAutoTable.finalY + 10;
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(14, finalY, pageWidth - 28, 30, 2, 2, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(15, 23, 42);
  doc.text('Key Strategic Takeaway:', 18, finalY + 7);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(51, 65, 85);
  doc.text(
    `Your store currently leaves an estimated ${analysis.revenueLeakageEstimate} in unrealized sales each month due to friction in mobile speed, trust guarantees, and checkout abandonment. Executing the top 10 fixes outlined below will immediately improve both conversion rate and customer acquisition efficiency (ROAS).`,
    18,
    finalY + 14,
    { maxWidth: pageWidth - 36 }
  );

  drawPageFooter();

  // ==========================================
  // PAGE 2+: TOP 10 PRIORITIZED FIX LIST
  // ==========================================
  doc.addPage();
  drawPageHeader(2);

  let currentY = 24;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(15, 23, 42);
  doc.text('2. Top Prioritized Issues (Ranked by Impact × Ease)', 14, currentY);
  currentY += 8;

  analysis.topIssues.forEach((issue, index) => {
    // Check if we need a new page
    if (currentY > pageHeight - 55) {
      drawPageFooter();
      doc.addPage();
      drawPageHeader(doc.getNumberOfPages());
      currentY = 24;
    }

    doc.setFillColor(248, 250, 252);
    doc.roundedRect(14, currentY, pageWidth - 28, 44, 2, 2, 'F');
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(14, currentY, pageWidth - 28, 44, 2, 2, 'S');

    // Issue header
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(15, 23, 42);
    doc.text(`#${index + 1}. [${issue.category}] ${issue.title}`, 18, currentY + 7);

    // Badges: Impact x Ease, Severity
    doc.setFontSize(8);
    doc.setTextColor(16, 185, 129);
    doc.text(
      `Priority Score: ${issue.priorityScore}/25 (Impact: ${issue.impact}/5, Ease: ${issue.ease}/5)`,
      18,
      currentY + 13
    );

    // Why it matters
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(71, 85, 105);
    doc.text('Why it matters:', 18, currentY + 19);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(51, 65, 85);
    doc.text(issue.explanation, 39, currentY + 19, { maxWidth: pageWidth - 60 });

    // Fix steps
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(16, 185, 129);
    doc.text('Exact Fix Steps:', 18, currentY + 27);

    doc.setFont('helvetica', 'normal');
    doc.setTextColor(51, 65, 85);
    const stepsText = issue.fixSteps.map((s, idx) => `${idx + 1}. ${s}`).slice(0, 2).join('   •   ');
    doc.text(stepsText, 18, currentY + 33, { maxWidth: pageWidth - 36 });

    currentY += 49;
  });

  drawPageFooter();

  // ==========================================
  // PAGE 3: AI DIRECT-RESPONSE COPYWRITING
  // ==========================================
  if (aiCopy) {
    doc.addPage();
    drawPageHeader(doc.getNumberOfPages());

    currentY = 24;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(15, 23, 42);
    doc.text('3. AI Copywriting Studio (High-Converting Rewrites)', 14, currentY);
    currentY += 8;

    doc.setFontSize(10);
    doc.setTextColor(71, 85, 105);
    doc.text('Tested direct-response alternatives ready to copy-paste into your Shopify theme:', 14, currentY);
    currentY += 8;

    aiCopy.heroRewrites.forEach((variant, vIdx) => {
      doc.setFillColor(241, 245, 249);
      doc.roundedRect(14, currentY, pageWidth - 28, 38, 2, 2, 'F');

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(15, 23, 42);
      doc.text(variant.title, 18, currentY + 6);

      doc.setFontSize(8.5);
      doc.setTextColor(16, 185, 129);
      doc.text(`Headline: "${variant.headline}"`, 18, currentY + 13);

      doc.setFont('helvetica', 'normal');
      doc.setTextColor(51, 65, 85);
      doc.text(`Subheadline: ${variant.subheadline}`, 18, currentY + 19, { maxWidth: pageWidth - 36 });

      doc.setFont('helvetica', 'bold');
      doc.text(`Primary CTA Button: [ ${variant.ctaText} ]`, 18, currentY + 26);

      doc.setFont('helvetica', 'italic');
      doc.setFontSize(8);
      doc.setTextColor(100, 116, 139);
      doc.text(`Psychology: ${variant.whyItConverts}`, 18, currentY + 32, { maxWidth: pageWidth - 36 });

      currentY += 44;
    });

    // Product description rewrite section
    if (currentY < pageHeight - 50) {
      doc.setFillColor(236, 253, 245);
      doc.roundedRect(14, currentY, pageWidth - 28, 48, 2, 2, 'F');

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(6, 78, 59);
      doc.text('Product Page Transformation Script (Hook & Transformation):', 18, currentY + 7);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(4, 120, 87);
      doc.text(`Opening Hook: "${aiCopy.productRewrite.hook}"`, 18, currentY + 14, { maxWidth: pageWidth - 36 });
      doc.text(`Problem Formulation: ${aiCopy.productRewrite.storyProblem}`, 18, currentY + 22, { maxWidth: pageWidth - 36 });
      doc.text(`Recommended Pricing Offer: ${aiCopy.productRewrite.recommendedPricingOffer}`, 18, currentY + 30, { maxWidth: pageWidth - 36 });
      doc.text(`Risk-Free Guarantee: ${aiCopy.productRewrite.riskReversalGuarantee}`, 18, currentY + 38, { maxWidth: pageWidth - 36 });
    }

    drawPageFooter();
  }

  return doc.output('arraybuffer') as unknown as Uint8Array;
}
